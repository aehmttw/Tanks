package tanks.tankson;

import tanks.Game;

import java.util.ArrayList;
import java.util.HashMap;

/**
 * The two-way table between property ids and the serial numbers {@link ObjectBuffer} writes in their place.
 * The build generates it into {@value #FILE}, where a property's number is its line number. Lines are only
 * ever appended, so the table of an older build is always a prefix of the table of a newer one.
 */
public final class PropertyIds
{
    public static final String FILE = "/tankson/property_ids.txt";

    /** number -> id. The numbers have no gaps, so the number is just the index. */
    private static volatile String[] ids;

    /** id -> number */
    private static HashMap<String, Integer> numbers;

    private PropertyIds()
    {
    }

    private static void load()
    {
        if (ids != null)
            return;

        synchronized (PropertyIds.class)
        {
            if (ids != null)
                return;

            ArrayList<String> lines = Game.game.fileManager.getInternalFileContents(FILE);
            if (lines.isEmpty())
                throw new RuntimeException("Missing " + FILE + ", it is generated by the updatePropertyIds build task");

            String[] i = new String[lines.size()];
            HashMap<String, Integer> n = new HashMap<>(lines.size() * 2);

            for (int num = 0; num < lines.size(); num++)
            {
                String id = lines.get(num).trim();
                i[num] = id;

                if (n.put(id, num) != null)
                    throw new RuntimeException("Duplicate property id in " + FILE + ": " + id);
            }

            numbers = n;
            ids = i;
        }
    }

    public static int size()
    {
        load();
        return ids.length;
    }

    /** The number of a property id, or -1 if it isn't in the table, as with ids added by extensions. */
    public static int toNumber(String id)
    {
        load();
        Integer num = numbers.get(id);
        return num == null ? -1 : num;
    }

    public static String toId(int num)
    {
        load();
        if (num < 0 || num >= ids.length)
            throw new RuntimeException("Unknown property number " + num + ", the data may be from a newer version of Tanks");

        return ids[num];
    }
}
